# print function with center, rjust and ljust methods
text = "Hello, World!"
print(text.center(20))
print(text.rjust(20))
print(text.ljust(20))
print(text.center(20, "*"))
print(text.rjust(20, "*"))
print(text.ljust(20, "*"))

